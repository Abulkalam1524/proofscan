"""Run OWASP ZAP in Docker against a target and save its json report.

    python -m benchmark.run_zap --target http://dvwa/ --network dvwa_default \
        --login-dvwa --out reports/zap-dvwa.json

ZAP gets the same logged in DVWA session as ProofScan, fetched outside both
tools, because DVWA's login form needs a user_token neither tool sends.
The generated plan is saved next to the report.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

import httpx

ZAP_IMAGE = "ghcr.io/zaproxy/zaproxy:stable"

# Left alone for the same reason ProofScan leaves them alone: requesting them
# changes the target, and everything scanned afterwards then means nothing. ZAP
# will happily log itself out halfway through a scan otherwise.
EXCLUDE = [
    r".*logout.*",
    r".*setup\.php.*",
    r".*security\.php.*",
    r".*phpinfo.*",
    # DVWA's two change password forms. ZAP filled one in on 8 Sep and changed
    # the admin password mid scan. ProofScan skips both, so ZAP does too.
    r".*vulnerabilities/csrf.*",
    r".*vulnerabilities/captcha.*",
]


def dvwa_session(base, username="admin", password="password", security="low"):
    """Log in to DVWA (user_token and all) and return a cookie header for ZAP."""
    with httpx.Client(base_url=base, follow_redirects=True, timeout=30) as client:
        page = client.get("/login.php")
        match = re.search(r"name=['\"]user_token['\"]\s+value=['\"]([^'\"]+)['\"]",
                          page.text)
        if not match:
            sys.exit("no user_token on DVWA's login page, is it really DVWA?")

        client.post("/login.php", data={
            "username": username, "password": password,
            "Login": "Login", "user_token": match.group(1),
        })

        session = client.cookies.get("PHPSESSID")
        if not session:
            sys.exit("DVWA did not hand out a session, check the credentials")

    # security=low matters as much as the login does. DVWA defaults this cookie
    # to "impossible", which is the fully patched build, and a scanner that
    # never sets it is scanning an application with nothing wrong with it.
    return f"PHPSESSID={session}; security={security}"


def build_plan(target, report_name, cookie=None, spider_minutes=3,
               scan_minutes=20, max_alerts=20):
    include = target.rstrip("/") + ".*"

    jobs = []

    if cookie:
        # one rule replacing the whole Cookie header, which is safe here only
        # because the session was fetched from outside and is the only cookie
        # the target needs
        jobs.append(f"""  - type: replacer
    parameters:
      deleteAllRules: true
    rules:
      - description: "session handed over from outside the scanner"
        matchType: req_header
        matchString: Cookie
        matchRegex: false
        replacementString: "{cookie}"
""")

    jobs.append(f"""  - type: passiveScan-config
    parameters:
      maxAlertsPerRule: {max_alerts}

  - type: spider
    parameters:
      context: target
      maxDuration: {spider_minutes}

  - type: passiveScan-wait

  - type: activeScan
    parameters:
      context: target
      maxScanDurationInMins: {scan_minutes}

  - type: report
    parameters:
      template: traditional-json
      reportDir: /zap/wrk
      reportFile: "{report_name}"
""")

    # single quoted on purpose: double quoted yaml treats \. as an escape and
    # ZAP dies before it starts
    excludes = "\n".join(f"        - '{pattern}'" for pattern in EXCLUDE)

    return f"""# Generated by benchmark/run_zap.py. Saved beside the report so the
# configuration behind a result is recorded rather than described.
env:
  contexts:
    - name: target
      urls:
        - "{target}"
      includePaths:
        - "{include}"
      excludePaths:
{excludes}
  parameters:
    failOnError: false
    progressToStdout: true

jobs:
{"".join(jobs)}"""


def main():
    parser = argparse.ArgumentParser(prog="benchmark.run_zap")
    parser.add_argument("--target", required=True,
                        help="url as ZAP's container sees it, eg http://dvwa/")
    parser.add_argument("--out", required=True, metavar="PATH",
                        help="where to write the json report")
    parser.add_argument("--network",
                        help="docker network to join, so ZAP can reach a target "
                             "that is itself a container")
    parser.add_argument("--login-dvwa", action="store_true",
                        help="log in to DVWA first and hand ZAP the session")
    parser.add_argument("--login-url",
                        help="base url to log in against, if it differs from "
                             "--target (the container name is not reachable "
                             "from here, 127.0.0.1 is)")
    parser.add_argument("--security", default="low",
                        help="DVWA security level cookie")
    parser.add_argument("--spider-minutes", type=int, default=3)
    parser.add_argument("--scan-minutes", type=int, default=20)
    args = parser.parse_args()

    out = Path(args.out).resolve()
    out.parent.mkdir(parents=True, exist_ok=True)

    cookie = None
    if args.login_dvwa:
        cookie = dvwa_session(args.login_url or args.target,
                              security=args.security)
        print(f"session for ZAP: {cookie}")

    plan = build_plan(args.target, out.name, cookie=cookie,
                      spider_minutes=args.spider_minutes,
                      scan_minutes=args.scan_minutes)

    plan_path = out.with_name(out.stem + "-plan.yaml")
    plan_path.write_text(plan, encoding="utf-8")
    print(f"plan written to {plan_path}")

    # Uncapped, ZAP ran Docker out of memory on a 16 GB laptop. 4 GB of heap in a
    # 5 GB container, so if it still runs out ZAP stops, not Docker.
    command = ["docker", "run", "--rm", "--memory", "5g",
               "-v", f"{out.parent.as_posix()}:/zap/wrk:rw"]
    if args.network:
        command += ["--network", args.network]
    command += [ZAP_IMAGE, "zap.sh", "-Xmx4g", "-cmd",
                "-autorun", f"/zap/wrk/{plan_path.name}"]

    print(" ".join(command), flush=True)
    result = subprocess.run(command)

    if not out.exists():
        sys.exit(f"ZAP finished with code {result.returncode} but wrote no "
                 f"report to {out}")

    print(f"\nreport: {out}  ({out.stat().st_size / 1024:.0f} kB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
